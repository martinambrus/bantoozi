// Assembles src/learn/kernel/accumulate.wat (SIMD) into src/learn/kernel/accumulate.wasm.ts (D-264).
//   pnpm --filter @bantoozi/ranker kernel:gen
// `--check` exits non-zero when the committed bytes differ from the source (the tests run it too).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import initWabt from 'wabt';

const dir = new URL('../src/learn/kernel/', import.meta.url);
const watPath = fileURLToPath(new URL('accumulate.wat', dir));
const tsPath = fileURLToPath(new URL('accumulate.wasm.ts', dir));

/** The base64 of the assembled kernel. */
export async function assembleKernel() {
  const wabt = await initWabt();
  const module = wabt.parseWat('accumulate.wat', readFileSync(watPath, 'utf8'), { simd: true });
  try {
    module.validate();
    const { buffer } = module.toBinary({ log: false, write_debug_names: false });
    return Buffer.from(buffer).toString('base64');
  } finally {
    module.destroy();
  }
}

export function renderKernelModule(base64) {
  return [
    '// Generated by scripts/gen-kernel.mjs from accumulate.wat: do not edit (D-264).',
    `export const ACCUMULATE_WASM_BASE64 = '${base64}';`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = renderKernelModule(await assembleKernel());
  if (process.argv.includes('--check')) {
    if (readFileSync(tsPath, 'utf8') !== rendered) {
      console.error(
        'accumulate.wasm.ts is out of date: run pnpm --filter @bantoozi/ranker kernel:gen',
      );
      process.exit(1);
    }
  } else {
    writeFileSync(tsPath, rendered);
  }
}
