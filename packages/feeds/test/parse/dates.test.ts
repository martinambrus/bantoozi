import { describe, expect, it } from 'vitest';

import { parseFeedDate } from '../../src/parse/index.js';

describe('parseFeedDate (spec 03 §6 published_at)', () => {
  it.each([
    // RFC 822/2822 (RSS pubDate)
    ['Fri, 25 Sep 2026 14:05:00 +0000', '2026-09-25T14:05:00.000Z'],
    ['Fri, 25 Sep 2026 14:05:00 GMT', '2026-09-25T14:05:00.000Z'],
    ['Fri, 25 Sep 2026 14:05 +0200', '2026-09-25T12:05:00.000Z'],
    ['Fri, 25 Sep 2026 14:05:00 -0530', '2026-09-25T19:35:00.000Z'],
    ['25 Sep 2026 14:05:00 UT', '2026-09-25T14:05:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 EST', '2026-09-24T13:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 PDT', '2026-09-24T15:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 CEST', '2026-09-24T06:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 +0200 (CEST)', '2026-09-24T06:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 +0200 CEST', '2026-09-24T06:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 GMT+0200', '2026-09-24T06:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 Z', '2026-09-24T08:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00 A', '2026-09-24T08:00:00.000Z'],
    ['Thursday, 24 September 2026 08:00:00 GMT', '2026-09-24T08:00:00.000Z'],
    ['Thu, 24 Sept. 2026 08:00:00 GMT', '2026-09-24T08:00:00.000Z'],
    ['Št, 24 Sep 2026 08:00:00 +0200', '2026-09-24T06:00:00.000Z'],
    ['Thu 24 Sep 2026 08:00:00 GMT', '2026-09-24T08:00:00.000Z'],
    ['Thursday, 24-Sep-26 08:00:00 GMT', '2026-09-24T08:00:00.000Z'],
    ['24 Sep 99 08:00 GMT', '1999-09-24T08:00:00.000Z'],
    ['24 Sep 49 08:00 GMT', '2049-09-24T08:00:00.000Z'],
    ['Thu, 24 Sep 2026 23:59:60 GMT', '2026-09-24T23:59:59.000Z'],
    ['  Thu,  24 Sep 2026   08:00:00   GMT  ', '2026-09-24T08:00:00.000Z'],
    ['Thu, 24 Sep 2026 08:00:00', '2026-09-24T08:00:00.000Z'],
    [
      'Thu Sep 24 2026 08:00:00 GMT+0200 (Central European Summer Time)',
      '2026-09-24T06:00:00.000Z',
    ],
    // RFC 3339 / ISO 8601 / W3C-DTF (Atom, JSON Feed, dc:date)
    ['2026-09-25T08:00:00Z', '2026-09-25T08:00:00.000Z'],
    ['2026-09-25T08:00:00.123456Z', '2026-09-25T08:00:00.123Z'],
    ['2026-09-25t08:00:00z', '2026-09-25T08:00:00.000Z'],
    ['2026-09-25T08:00:00+02:00', '2026-09-25T06:00:00.000Z'],
    ['2026-09-25T08:00:00-0330', '2026-09-25T11:30:00.000Z'],
    ['2026-09-25T08:00:00+02', '2026-09-25T06:00:00.000Z'],
    ['2026-09-25T08:00+02:00', '2026-09-25T06:00:00.000Z'],
    ['2026-09-25 08:00:00', '2026-09-25T08:00:00.000Z'],
    ['2026-09-25 08:00:00 UTC', '2026-09-25T08:00:00.000Z'],
    ['2026-09-25', '2026-09-25T00:00:00.000Z'],
    ['2026-09', '2026-09-01T00:00:00.000Z'],
    ['2026', '2026-01-01T00:00:00.000Z'],
    // Last resort for strings with an explicit zone.
    ['September 24, 2026 08:00 GMT', '2026-09-24T08:00:00.000Z'],
  ])('%s → %s', (input, expected) => {
    expect(parseFeedDate(input)?.toISOString()).toBe(expected);
  });

  it.each([
    [''],
    ['   '],
    ['yesterday'],
    ['last Tuesday'],
    ['32/13/2026 25:61'],
    ['Mon, 30 Feb 2026 10:00:00 GMT'],
    ['2026-02-30T10:00:00Z'],
    ['2026-13-01'],
    ['2026-09-25T24:00:00Z'],
    ['2026-09-25T08:60:00Z'],
    ['2026-09-25T08:00:00+25:00'],
    ['Thu, 24 Sep 2026 08:00:00 IST'],
    ['Thu, 24 Foo 2026 08:00:00 GMT'],
    ['Thu, 24 Sep 2026 08:00:00 +0200 garbage'],
    ['0000-00-00 00:00:00'],
    ['0099-01-01T00:00:00Z'],
    ['September 24, 2026 08:00'],
    ['x'.repeat(200)],
  ])('%s → null', (input) => {
    expect(parseFeedDate(input)).toBeNull();
  });

  it('does not depend on the process time zone', () => {
    // A zoneless date is UTC; V8's Date would read it in local time.
    const date = parseFeedDate('Thu, 24 Sep 2026 23:59:59');
    expect(date?.getTime()).toBe(Date.UTC(2026, 8, 24, 23, 59, 59));
  });
});
